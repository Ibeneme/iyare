import React, { useEffect, useState } from "react";
import { useDispatch } from "react-redux";
import "./DiscountsManager.css";
import { AppDispatch } from "../../../Redux/store";
import {
  addDiscount,
  deleteDiscount,
  fetchDiscounts,
  updateDiscount,
} from "../../../Redux/Slices/SettingsSlice";
import ModalDropdown from "../../../Components/Modal/ModalDropdown";

// Define an interface for the discount object to improve type safety
interface Discount {
  _id: string; // Assuming an ID is generated by the backend
  title: string;
  percentage: number;
}

const DiscountsManager: React.FC = () => {
  const dispatch = useDispatch<AppDispatch>();
  const [discounts, setDiscounts] = useState<Discount[]>([]);
  const [newTitle, setNewTitle] = useState("");
  const [newPercentage, setNewPercentage] = useState<number>(0);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // State for the edit modal
  const [showEditModal, setShowEditModal] = useState(false);
  const [editDiscount, setEditDiscount] = useState<Discount | null>(null);
  const [editIndex, setEditIndex] = useState<number | null>(null);
  const [editTitle, setEditTitle] = useState("");
  const [editPercentage, setEditPercentage] = useState<number>(0);

  // State for the delete confirmation modal
  const [showDeleteModal, setShowDeleteModal] = useState(false);
  const [deleteIndex, setDeleteIndex] = useState<number | null>(null);
  const [deleteDiscountTitle, setDeleteDiscountTitle] = useState("");

  useEffect(() => {
    const fetch = async () => {
      setLoading(true);
      setError(null);
      try {
        const data = await dispatch(fetchDiscounts()).unwrap();
        console.log(data, 'data')
        const extracted = Array.isArray(data.discounts) ? data.discounts : [];
        setDiscounts(extracted);
      } catch (err: any) {
        setError(err.message || "Failed to fetch discounts.");
      } finally {
        setLoading(false);
      }
    };
    fetch();
  }, [dispatch]);

  const handleAdd = async () => {
    if (!newTitle.trim() || newPercentage <= 0) {
      setError("Please provide a valid title and percentage.");
      return;
    }
    setLoading(true);
    try {
      const updated = await dispatch(
        addDiscount({ title: newTitle, percentage: newPercentage })
      ).unwrap();
      setDiscounts(updated);
      setNewTitle("");
      setNewPercentage(0);
      setError(null);
    } catch (err) {
      setError("Failed to add discount.");
    } finally {
      setLoading(false);
    }
  };

  const handleUpdate = async () => {
    if (editIndex === null || !editTitle.trim() || editPercentage <= 0) {
      setError("Please provide a valid title and percentage.");
      return;
    }
    setLoading(true);
    try {
      const updatedList = await dispatch(
        updateDiscount({
          index: editIndex,
          title: editTitle,
          percentage: editPercentage,
        })
      ).unwrap();
      setDiscounts(updatedList);
      handleCloseEditModal();
      setError(null);
    } catch (err) {
      setError("Failed to update discount.");
    } finally {
      setLoading(false);
    }
  };

  const handleDelete = async () => {
    if (deleteIndex === null) return;

    setLoading(true);
    try {
      const updated = await dispatch(deleteDiscount(deleteIndex)).unwrap();
      setDiscounts(updated);
      handleCloseDeleteModal(); // Close the modal on success
      setError(null);
    } catch (err) {
      setError("Failed to delete discount.");
    } finally {
      setLoading(false);
    }
  };

  const handleOpenEditModal = (discount: Discount, index: number) => {
    setEditDiscount(discount);
    setEditIndex(index);
    setEditTitle(discount.title);
    setEditPercentage(discount.percentage);
    setShowEditModal(true);
  };

  const handleCloseEditModal = () => {
    setShowEditModal(false);
    setEditDiscount(null);
    setEditIndex(null);
    setEditTitle("");
    setEditPercentage(0);
  };

  const handleOpenDeleteModal = (index: number, title: string) => {
    setDeleteIndex(index);
    setDeleteDiscountTitle(title);
    setShowDeleteModal(true);
  };

  const handleCloseDeleteModal = () => {
    setShowDeleteModal(false);
    setDeleteIndex(null);
    setDeleteDiscountTitle("");
  };

  return (
    <div className="discounts-manager">
      <h2 className="dm-title">Discounts Manager</h2>

      <div className="dm-form">
        <input
          type="text"
          placeholder="Discount title"
          value={newTitle}
          onChange={(e) => setNewTitle(e.target.value)}
        />
        <input
          type="number"
          placeholder="Percentage"
          value={newPercentage}
          onChange={(e) => setNewPercentage(Number(e.target.value))}
        />
        <button onClick={handleAdd} disabled={loading}>
          Add Discount
        </button>
      </div>

      {loading && <p className="dm-status">Loading...</p>}
      {error && <p className="dm-error">{error}</p>}

      <ul className="dm-list">
        {discounts.map((d, index) => (
          <li key={d._id || index} className="dm-item">
            <div className="dm-info">
              <span className="dm-label">{d.title}</span>
              <span className="dm-percent">{d.percentage}%</span>
            </div>
            <div className="dm-actions">
              <button onClick={() => handleOpenEditModal(d, index)}>
                Edit
              </button>
              <button onClick={() => handleOpenDeleteModal(index, d.title)}>
                Delete
              </button>
            </div>
          </li>
        ))}
      </ul>

      {/* Edit Modal */}
      {showEditModal && editDiscount && (
        <ModalDropdown onClose={handleCloseEditModal}>
          <div className="">
            <div className="">
              <div className="">
                <h3>Edit Discount</h3>
                <button className="close-btn" onClick={handleCloseEditModal}>
                  &times;
                </button>
              </div>
              <div className="modal-body">
                <div style={{ marginTop: "24px" }}>
                  <label htmlFor="edit-title">Discount Title</label>
                  <input
                    id="edit-title"
                    type="text"
                    value={editTitle}
                    onChange={(e) => setEditTitle(e.target.value)}
                    placeholder="Discount title"
                  />
                </div>
                <div style={{ marginTop: "24px" }}>
                  <label htmlFor="edit-percentage">Percentage</label>
                  <input
                    id="edit-percentage"
                    type="number"
                    value={editPercentage}
                    onChange={(e) => setEditPercentage(Number(e.target.value))}
                    placeholder="Percentage"
                  />
                </div>
              </div>
              <div className="modal-footer">
                <button
                  className="cancel-btn"
                  onClick={handleCloseEditModal}
                  style={{
                    fontSize: 13,
                    borderRadius: 48,
                  }}
                >
                  Cancel
                </button>
                <button
                  className="save-btn"
                  onClick={handleUpdate}
                  disabled={loading}
                  style={{
                    backgroundColor: `var(--yellow)`,
                    color: `var(--dark-green)`,
                    border: `1px solid var(--dark-green)`,
                    fontSize: 13,
                    borderRadius: 48,
                  }}
                >
                  Save Changes
                </button>
              </div>
            </div>
          </div>
        </ModalDropdown>
      )}

      {/* Delete Confirmation Modal */}
      {showDeleteModal && (
        <ModalDropdown onClose={handleCloseDeleteModal}>
          <div className="">
            <div className="">
              <div className="">
                <h3>Confirm Deletion</h3>
                <button className="close-btn" onClick={handleCloseDeleteModal}>
                  &times;
                </button>
              </div>
              <div className="modal-body">
                <p>
                  Are you sure you want to delete the discount "{deleteDiscountTitle}"?
                </p>
                <p>This action cannot be undone.</p>
              </div>
              <div className="modal-footer">
                <button
                  className="cancel-btn"
                  onClick={handleCloseDeleteModal}
                  style={{
                    fontSize: 13,
                    borderRadius: 48,
                  }}
                >
                  Cancel
                </button>
                <button
                  className="save-btn"
                  onClick={handleDelete}
                  disabled={loading}
                  style={{
                    backgroundColor: `#dc3545`, // A red color for delete
                    color: `#fff`,
                    border: `1px solid #dc3545`,
                    fontSize: 13,
                    borderRadius: 48,
                  }}
                >
                  Confirm Delete
                </button>
              </div>
            </div>
          </div>
        </ModalDropdown>
      )}
    </div>
  );
};

export default DiscountsManager;